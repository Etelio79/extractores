function titulosPosibles(datos) {
  const vistos = new Set();
  return [datos.titulo, datos.ingles, datos.original].filter((t) => {
    const n = normalizar(t);
    if (!n || vistos.has(n)) return false;
    vistos.add(n);
    return true;
  });
}

const RELLENO = new Set(['ver', 'online', 'gratis', 'latino', 'castellano', 'subtitulado', 'espanol', 'audio', 'hd', 'full', 'completa', 'pelicula', 'serie']);
const VACIAS = new Set(['the', 'and', 'of', 'a', 'el', 'la', 'los', 'las', 'de', 'del', 'y', 'en', 'un', 'una']);

function limpiarTitulo(t) {
  const n = normalizar(String(t || '').replace(/\([^)]*\)|\[[^\]]*\]/g, ' '));
  const limpio = n.split(' ').filter((p) => !RELLENO.has(p)).join(' ');
  return limpio || n;
}

function parecido(a, b) {
  const x = limpiarTitulo(a);
  const y = limpiarTitulo(b);
  if (!x || !y) return 0;
  if (x === y) return 1;
  const [corto, largo] = x.length <= y.length ? [x, y] : [y, x];
  const contiene = ` ${largo} `.includes(` ${corto} `) ? 0.6 + (0.4 * corto.length) / largo.length : 0;
  const px = new Set(x.split(' ').filter((p) => !VACIAS.has(p)));
  const py = new Set(y.split(' ').filter((p) => !VACIAS.has(p)));
  let comunes = 0;
  for (const p of px) if (py.has(p)) comunes++;
  const palabras = px.size && py.size ? comunes / Math.max(px.size, py.size) : 0;
  return Math.max(contiene, palabras);
}

function audioDe(t) {
  const s = normalizar(t);
  if (!s) return '';
  if (/latino|\blat\b|latam|mexic|\bmx\b|419|doblaje latino/.test(s)) return 'Latino';
  if (/castellano|espana|\bcast\b|\besp\b|\bes es\b/.test(s)) return 'Castellano';
  if (/subtitulad|\bvose\b|\bsub\b|\bsubs\b|\bvo\b|japones|ingles|english|original/.test(s)) return 'Subtitulado';
  if (/espanol|spanish/.test(s)) return 'Español';
  return '';
}

const TELE = typeof __plugin_sleep !== 'function' && typeof __cheerio_load === 'function';

function tarjeta(info) {
  const s = {
    name: info.servidor ? `${info.fuente} (${info.servidor})` : info.fuente,
    title: info.titulo,
    url: info.url,
    quality: `Calidad: ${info.calidad || 'Auto'}`,
    provider: info.fuente
  };
  if (info.tamano) s.size = `Tamaño: ${info.tamano}`;
  if (info.audio) s.language = `Audio: ${info.audio}`;
  if (TELE) {
    s.size = [s.quality, s.size].filter(Boolean).join(' • ');
    s.quality = s.name;
  }
  if (info.headers && Object.keys(info.headers).length) s.headers = info.headers;
  return s;
}

function pesoCalidad(c) {
  if (/4k/i.test(c)) return 2160;
  return Number((String(c || '').match(/(\d{3,4})p/i) || [])[1]) || 0;
}

function pesoAudio(a) {
  return { Latino: 3, 'Español': 2, Castellano: 1 }[a] || 0;
}

async function armar(lista, titulo, fuente) {
  const vistos = new Set();
  const tarjetas = [];
  for (const item of lista) {
    if (!item || !item.url || vistos.has(item.url)) continue;
    vistos.add(item.url);
    if (!hostPermitido(item.url, item.servidor)) continue;
    tarjetas.push({
      orden: pesoAudio(item.audio || '') * 10000 + pesoCalidad(item.calidad || ''),
      t: tarjeta({
        titulo,
        calidad: item.calidad || '',
        audio: item.audio || '',
        fuente,
        servidor: nombreServidor(item.url, item.servidor),
        url: item.url,
        headers: item.referer ? { Referer: item.referer, 'User-Agent': UA } : { 'User-Agent': UA }
      })
    });
  }
  return tarjetas.sort((a, b) => b.orden - a.orden).map((x) => x.t);
}

async function enCadena(tareas, procesar) {
  const pendientes = tareas.map((tarea) => Promise.resolve().then(tarea).catch(() => []));
  for (const pendiente of pendientes) {
    const lista = await pendiente;
    if (!lista || !lista.length) continue;
    const salida = await procesar(lista);
    if (salida.length) return salida;
  }
  return [];
}

async function enOrden(tareas, procesar) {
  for (const tarea of tareas) {
    const lista = await Promise.resolve().then(tarea).catch(() => []);
    if (!lista || !lista.length) continue;
    const salida = await procesar(lista);
    if (salida.length) return salida;
  }
  return [];
}

function limitar(buscador, respaldo) {
  return (...argumentos) => {
    inicio = Date.now();
    caidos.clear();
    registro = [];
    const trabajo = conLimite(Promise.resolve().then(() => buscador(...argumentos)), CIERRE, null);
    return respaldo ? trabajo.then((salida) => (salida && salida.length ? salida : respaldo(salida === null))) : trabajo.then((salida) => salida || []);
  };
}

const FUENTE = 'PelisPlus';
const BASES = ['https://pelisplushd.bz', 'https://www.pelisplushd.la', 'https://ww3.pelisplus.to'];

async function buscar(base, titulos, tipo) {
  for (const titulo of titulos) {
    const html = await texto(`${base}/search?s=${encodeURIComponent(titulo)}`);
    let mejor = null;
    let puntos = 0;
    const patron = /<a[^>]+class="[^"]*Posters-link[^"]*"[^>]*href="([^"]+)"[\s\S]*?<div class="listing-content">[\s\S]*?<p[^>]*>([\s\S]*?)<\/p>|<a[^>]+href="([^"]+)"[^>]*class="[^"]*Posters-link[\s\S]*?<div class="listing-content">[\s\S]*?<p[^>]*>([\s\S]*?)<\/p>/gi;
    let m;
    while ((m = patron.exec(html))) {
      const href = m[1] || m[3];
      const nombre = limpiarHtml(m[2] || m[4]);
      if ((tipo === 'movie') !== /\/pelicula\//.test(href)) continue;
      const s = parecido(nombre, titulo);
      if (s > puntos) {
        puntos = s;
        mejor = absoluta(href, base);
      }
    }
    if (mejor && puntos >= 0.8) return mejor;
  }
  return null;
}

async function enlacesPagina(html, base, pagina) {
  const script = (html.match(/var video = \[\];([\s\S]*?)<\/script>/) || [])[1] || '';
  const lista = [...new Set(script.match(/https?:\/\/[^'"\s<>\\]+/g) || [])].map((u) => ({ url: u, referer: pagina }));
  if (lista.length) return lista;
  const tareas = [];
  const pl = /<li\b[^>]*(?:data-url|data-id|class=["'][^"']*playurl)[^>]*>([\s\S]*?)<\/li>/gi;
  let m;
  while ((m = pl.exec(html))) {
    const etiqueta = m[0].slice(0, m[0].indexOf('>') + 1);
    const idioma = (etiqueta.match(/data-name=["']([^"']*)["']/) || [])[1] || limpiarHtml(m[1]);
    const audio = audioDe(idioma);
    if (audio === 'Subtitulado') continue;
    const directo = (etiqueta.match(/data-url=["']([^"']+)["']/) || [])[1];
    const id = (etiqueta.match(/data-id=["']([^"']+)["']/) || [])[1];
    const clase = (etiqueta.match(/data-tipo=["']([^"']+)["']/) || [])[1];
    if (directo) {
      tareas.push(Promise.resolve({ url: absoluta(directo, base), audio, referer: pagina }));
    } else if (id && clase) {
      tareas.push(texto(`${base}/ajax/embed?id=${encodeURIComponent(id)}&tipo=${encodeURIComponent(clase)}`, { headers: { Referer: pagina, 'X-Requested-With': 'XMLHttpRequest' } }).then((t) => {
        let url = t.trim();
        try {
          const d = JSON.parse(url);
          url = d.url || '';
        } catch (e) {}
        return /^https?:/.test(url) ? { url, audio, referer: pagina } : null;
      }));
    }
  }
  const general = audioDe((html.match(/Español Latino|Castellano/i) || [''])[0]);
  const ps = /<span[^>]*\burl=["']([^"']+)["'][^>]*>/gi;
  while ((m = ps.exec(html))) tareas.push(Promise.resolve({ url: absoluta(m[1], base), audio: general, referer: pagina }));
  const opciones = (html.match(/var\s+options\s*=\s*(\{[\s\S]*?\});/) || [])[1];
  if (opciones) {
    try {
      const o = JSON.parse(opciones.replace(/'/g, '"').replace(/,\s*}/g, '}'));
      for (const clave of Object.keys(o)) {
        const audio = audioDe(clave);
        if (!audio || audio === 'Subtitulado') continue;
        for (const item of o[clave] || []) if (item && item.url) tareas.push(Promise.resolve({ url: item.url, audio, referer: pagina }));
      }
    } catch (e) {}
  }
  return (await Promise.all(tareas)).filter(Boolean);
}

async function getStreams(tmdbId, mediaType, season, episode) {
  try {
    const tipo = mediaType === 'movie' ? 'movie' : 'tv';
    const datos = await datosTmdb(tmdbId, tipo);
    if (!datos) return [];
    const temporada = Number(season) || 1;
    const episodio = Number(episode) || 1;
    const enBase = async (base) => {
      let pagina = await buscar(base, titulosPosibles(datos), tipo);
      if (!pagina) return [];
      if (tipo === 'tv') pagina = `${pagina.replace(/\/+$/, '')}/temporada/${temporada}/capitulo/${episodio}`;
      return enlacesPagina(await texto(pagina), base, pagina);
    };
    return await enCadena(BASES.map((base) => () => enBase(base)), (lista) => armar(lista, encabezado(datos, tipo, temporada, episodio), FUENTE));
  } catch (e) {
    console.log(`[${FUENTE}] ${e.message}`);
    return [];
  }
}

